interface LanguageContextValue {
  lang: LangCode
  setLang: (l: LangCode) => void
  t: (key: string) => string
}

const LanguageContext = React.createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<LangCode>("en")

  React.useEffect(() => {
    const stored = typeof window !== "undefined" ? window.localStorage.getItem("medrelay.lang") : null
    const validCodes = LANGUAGES.map(l => l.code)
    if (validCodes.includes(stored as any)) {
      setLangState(stored as LangCode)
    }
  }, [])

  const setLang = React.useCallback((l: LangCode) => {
    setLangState(l)
    if (typeof window !== "undefined") window.localStorage.setItem("medrelay.lang", l)
  }, [])

  const t = React.useCallback(
    (key: string) => DICT[key]?.[lang] ?? DICT[key]?.en ?? key,
    [lang]
  )

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const ctx = React.useContext(LanguageContext)
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider")
  return ctx
}
